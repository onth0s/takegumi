/**
 * Build-time script that reads gnd/schemas/canvas.yaml (single source of
 * truth for data-model defaults) and regenerates
 * src/constants/_yaml-defaults.generated.ts.
 *
 * Hand-maintained constants (padding, import width, snap threshold, etc.)
 * are NOT in the YAML and must be added directly in canvasDefaults.ts.
 */

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import yaml from "js-yaml";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "..");
const YAML_PATH = resolve(ROOT, "gnd/schemas/canvas.yaml");
const OUT_PATH = resolve(ROOT, "src/constants/_yaml-defaults.generated.ts");

// ---------------------------------------------------------------------------
// Mapping from YAML property path → exported constant name.
// Paths are dot-separated segments into the schema: e.g.
//   WTextGroup.style.opacity → DEFAULT_WTG_OPACITY
// ---------------------------------------------------------------------------
const PATH_TO_CONST = {
  "WProject.grid.size":                 "DEFAULT_GRID_SIZE",
  "WProject.grid.snapEnabled":          "DEFAULT_GRID_SNAP_ENABLED",
  "WProject.grid.showGrid":             "DEFAULT_GRID_SHOW_GRID",
  "WProject.canvasTheme":               "DEFAULT_CANVAS_THEME",
  "WTextGroup.style.opacity":           "DEFAULT_WTG_OPACITY",
  "WTextGroup.style.backgroundColor":   "DEFAULT_WTG_BACKGROUND_COLOR",
  "WTextGroup.style.width":             "DEFAULT_WTG_WIDTH",
  "WTextGroup.style.borderRadius":      "DEFAULT_WTG_BORDER_RADIUS",
  "WTextGroup.style.borderWidth":       "DEFAULT_WTG_BORDER_WIDTH",
  "WTextGroup.style.shapeType":         "DEFAULT_WTG_SHAPE_TYPE",
  "WTextBlock.style.fontSize":          "DEFAULT_WTB_FONT_SIZE",
  "WTextBlock.style.fontWeight":        "DEFAULT_WTB_FONT_WEIGHT",
  "WTextBlock.style.color":             "DEFAULT_WTB_COLOR",
  "WTextBlock.style.textAlign":         "DEFAULT_WTB_TEXT_ALIGN",
  "WTextBlock.style.opacity":           "DEFAULT_WTB_OPACITY",
  "WTextBlock.style.backgroundOpacity": "DEFAULT_WTB_BACKGROUND_OPACITY",
};

// ---------------------------------------------------------------------------
// Walk the schema tree and collect { path, value } for every node that has
// a `default` key.
// ---------------------------------------------------------------------------
const SKIP_KEYS = new Set([
  "type", "description", "enum", "minimum", "maximum",
  "nullable", "format", "default", "items", "$ref",
]);

function collectDefaults(node, prefix = "") {
  const results = [];
  if (node && typeof node === "object") {
    if ("default" in node && prefix) {
      results.push({ path: prefix, value: node.default });
    }
    for (const [key, val] of Object.entries(node)) {
      if (!val || typeof val !== "object" || SKIP_KEYS.has(key)) continue;
      // Skip "properties" in the path since it's just a YAML schema wrapper
      const childPrefix = key === "properties"
        ? prefix
        : prefix ? `${prefix}.${key}` : key;
      results.push(...collectDefaults(val, childPrefix));
    }
  }
  return results;
}

// ---------------------------------------------------------------------------
// Format a JS value for TypeScript output.
// ---------------------------------------------------------------------------
function fmt(val) {
  if (typeof val === "string") return JSON.stringify(val);
  if (typeof val === "boolean") return String(val);
  if (typeof val === "number") return String(val);
  return JSON.stringify(val);
}

// ---------------------------------------------------------------------------
// Main
// ---------------------------------------------------------------------------
function main() {
  const raw = readFileSync(YAML_PATH, "utf-8");
  const schema = yaml.load(raw);

  const entries = collectDefaults(schema);

  const lines = [
    "// ────────────────────────────────────────────────────────────────────────────",
    "// DO NOT EDIT — This file is auto-generated by scripts/generate-defaults.mjs",
    "// from gnd/schemas/canvas.yaml (single source of truth).",
    "// ────────────────────────────────────────────────────────────────────────────",
    "",
    "// Grid & theme",
    ...entries
      .filter((e) => e.path.startsWith("WProject"))
      .map((e) => {
        const name = PATH_TO_CONST[e.path];
        if (!name) throw new Error(`No constant mapping for YAML path "${e.path}"`);
        const comment = e.path.replace(/^WProject\./, "");
        return `/** ${comment} */\nexport const ${name} = ${fmt(e.value)};`;
      }),
    "",
    "// WTextGroup",
    ...entries
      .filter((e) => e.path.startsWith("WTextGroup"))
      .map((e) => {
        const name = PATH_TO_CONST[e.path];
        if (!name) throw new Error(`No constant mapping for YAML path "${e.path}"`);
        const comment = e.path.replace(/^WTextGroup\./, "");
        return `/** ${comment} */\nexport const ${name} = ${fmt(e.value)};`;
      }),
    "",
    "// WTextBlock",
    ...entries
      .filter((e) => e.path.startsWith("WTextBlock"))
      .map((e) => {
        const name = PATH_TO_CONST[e.path];
        if (!name) throw new Error(`No constant mapping for YAML path "${e.path}"`);
        const comment = e.path.replace(/^WTextBlock\./, "");
        return `/** ${comment} */\nexport const ${name} = ${fmt(e.value)};`;
      }),
    "",
  ];

  // Ensure output directory exists
  mkdirSync(dirname(OUT_PATH), { recursive: true });
  writeFileSync(OUT_PATH, lines.join("\n"), "utf-8");
  console.log(`✓ Generated ${OUT_PATH}`);
}

main();
